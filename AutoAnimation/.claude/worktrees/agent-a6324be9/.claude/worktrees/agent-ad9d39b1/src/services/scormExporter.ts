/**
 * Create a SCORM-compliant ZIP package containing the video and SCORM wrapper.
 *
 * @param videoBlob - The exported video as a Blob
 * @param options - SCORM packaging options
 * @returns Promise resolving to the ZIP blob and suggested filename
 */
export async function createSCORMPackage(videoBlob: Blob, options: SCORMExportOptions): Promise<SCORMPackageResult> {
  const version = options.version || '1.2'
  const completionThreshold = options.completionThreshold ?? 80
  const videoFilename = options.videoFilename || 'video.mp4'

  // Generate SCORM files
  const manifest = version === '1.2' ? generateManifest12(options) : generateManifest2004(options)

  const scormJS = generateScormAPI(version, completionThreshold)
  const playerHTML = generatePlayerHTML(options)

  // Use JSZip for packaging (dynamically imported)
  const { default: JSZip } = await import('jszip')
  const zip = new JSZip()

  // Add files to the ZIP
  zip.file('imsmanifest.xml', manifest)
  zip.file('scormAPI.js', scormJS)
  zip.file('index.html', playerHTML)
  zip.file(videoFilename, videoBlob)

  // Generate the ZIP blob
  const zipBlob = await zip.generateAsync({
    type: 'blob',
    compression: 'DEFLATE',
    compressionOptions: { level: 6 },
  })

  const safeTitle = options.title.replace(/[^a-zA-Z0-9-_]/g, '_').substring(0, 50)
  const filename = `${safeTitle}_SCORM_${version.replace('.', '')}.zip`

  return { blob: zipBlob, filename }
}

/**
 * Trigger a browser download of the SCORM package.
 */
export function downloadSCORMPackage(result: SCORMPackageResult): void {
  const url = URL.createObjectURL(result.blob)
  const a = document.createElement('a')
  a.href = url
  a.download = result.filename
  document.body.appendChild(a)
  a.click()
  document.body.removeChild(a)
  URL.revokeObjectURL(url)
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function escapeXml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;')
}

function escapeHtml(str: string): string {
  return str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
}
