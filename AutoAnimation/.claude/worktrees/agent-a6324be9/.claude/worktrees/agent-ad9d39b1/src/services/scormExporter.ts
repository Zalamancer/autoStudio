/**
 * SCORM Export Service
 *
 * Packages a ProAnimate video export as a SCORM 1.2 or SCORM 2004 compatible
 * ZIP file that can be uploaded to LMS platforms (Moodle, Blackboard, Canvas,
 * Cornerstone, etc.).
 *
 * The SCORM package includes:
 * - imsmanifest.xml (course manifest)
 * - scormAPI.js (SCORM API adapter)
 * - index.html (launcher HTML page with video player)
 * - The exported video file
 *
 * The video player auto-reports completion to the LMS when the video finishes.
 */

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export type SCORMVersion = '1.2' | '2004'

export interface SCORMExportOptions {
  /** SCORM version (default: '1.2') */
  version?: SCORMVersion
  /** Course title */
  title: string
  /** Course description (optional) */
  description?: string
  /** Organization / author name */
  organization?: string
  /** Minimum percentage of video that must be watched for completion (0-100, default: 80) */
  completionThreshold?: number
  /** Video filename (default: 'video.mp4') */
  videoFilename?: string
}

export interface SCORMPackageResult {
  /** The ZIP blob ready for download */
  blob: Blob
  /** Suggested filename */
  filename: string
}

