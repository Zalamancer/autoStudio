function generatePlayerHTML(options: SCORMExportOptions): string {
  const title = escapeHtml(options.title)
  const videoFile = options.videoFilename || 'video.mp4'
  const threshold = options.completionThreshold || 80

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${title}</title>
  <script src="scormAPI.js"></script>
  <style>
    * { margin: 0; padding: 0; box-sizing: border-box; }
    body {
      background: #111;
      color: #fff;
      font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
      display: flex;
      flex-direction: column;
      align-items: center;
      justify-content: center;
      min-height: 100vh;
      padding: 20px;
    }
    .container {
      max-width: 1280px;
      width: 100%;
    }
    h1 {
      font-size: 1.5rem;
      margin-bottom: 16px;
      text-align: center;
      opacity: 0.9;
    }
    .video-wrapper {
      position: relative;
      width: 100%;
      border-radius: 12px;
      overflow: hidden;
      box-shadow: 0 8px 32px rgba(0,0,0,0.5);
      background: #000;
    }
    video {
      width: 100%;
      display: block;
    }
    .progress-bar {
      height: 4px;
      background: #333;
      border-radius: 2px;
      margin-top: 16px;
      overflow: hidden;
    }
    .progress-fill {
      height: 100%;
      background: linear-gradient(90deg, #8b5cf6, #a78bfa);
      width: 0%;
      transition: width 0.3s ease;
      border-radius: 2px;
    }
    .status {
      margin-top: 12px;
      text-align: center;
      font-size: 0.875rem;
      opacity: 0.7;
    }
    .status.complete {
      color: #10b981;
      opacity: 1;
      font-weight: 600;
    }
  </style>
</head>
<body>
  <div class="container">
    <h1>${title}</h1>
    <div class="video-wrapper">
      <video id="player" controls preload="auto">
        <source src="${escapeHtml(videoFile)}" type="video/mp4">
        Your browser does not support the video element.
      </video>
    </div>
    <div class="progress-bar">
      <div class="progress-fill" id="progressFill"></div>
    </div>
    <div class="status" id="status">Watch at least ${threshold}% to complete this module</div>
  </div>

  <script>
    (function() {
      var video = document.getElementById('player');
      var progressFill = document.getElementById('progressFill');
      var statusEl = document.getElementById('status');
      var startTime = Date.now();
      var completed = false;
      var maxProgress = 0;

      // Initialize SCORM
      if (window.ScormAdapter) {
        window.ScormAdapter.initialize();
      }

      video.addEventListener('timeupdate', function() {
        if (!video.duration) return;
        var progress = (video.currentTime / video.duration) * 100;
        maxProgress = Math.max(maxProgress, progress);
        progressFill.style.width = maxProgress + '%';

        if (window.ScormAdapter) {
          window.ScormAdapter.setProgress(maxProgress);
        }

        if (!completed && maxProgress >= ${threshold}) {
          completed = true;
          statusEl.textContent = 'Module completed!';
          statusEl.className = 'status complete';
        }
      });

      video.addEventListener('ended', function() {
        maxProgress = 100;
        progressFill.style.width = '100%';
        if (window.ScormAdapter) {
          window.ScormAdapter.setComplete();
          var elapsed = Math.floor((Date.now() - startTime) / 1000);
          window.ScormAdapter.setSessionTime(elapsed);
        }
        if (!completed) {
          completed = true;
          statusEl.textContent = 'Module completed!';
          statusEl.className = 'status complete';
        }
      });

      window.addEventListener('beforeunload', function() {
        if (window.ScormAdapter) {
          var elapsed = Math.floor((Date.now() - startTime) / 1000);
          window.ScormAdapter.setSessionTime(elapsed);
          window.ScormAdapter.terminate();
        }
      });
    })();
  </script>
</body>
</html>`
}

