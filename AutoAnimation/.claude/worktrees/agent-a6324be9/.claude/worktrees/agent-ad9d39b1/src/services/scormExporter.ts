function generateScormAPI(version: SCORMVersion, completionThreshold: number): string {
  if (version === '1.2') {
    return `/**
 * SCORM 1.2 API Adapter
 * Generated by ProAnimate SCORM Exporter
 */
(function() {
  'use strict';

  var COMPLETION_THRESHOLD = ${completionThreshold / 100};
  var api = null;
  var initialized = false;

  // Find the SCORM API object in parent/opener frames
  function findAPI(win) {
    var attempts = 0;
    while (win && !win.API && attempts < 10) {
      attempts++;
      if (win.opener && win.opener !== win) {
        win = win.opener;
      } else if (win.parent && win.parent !== win) {
        win = win.parent;
      } else {
        break;
      }
    }
    return win ? win.API || null : null;
  }

  function getAPI() {
    if (api) return api;
    api = findAPI(window);
    if (!api && window.opener) {
      api = findAPI(window.opener);
    }
    return api;
  }

  window.ScormAdapter = {
    initialize: function() {
      var lmsAPI = getAPI();
      if (lmsAPI) {
        var result = lmsAPI.LMSInitialize('');
        initialized = result === 'true' || result === true;
        if (initialized) {
          lmsAPI.LMSSetValue('cmi.core.lesson_status', 'incomplete');
          lmsAPI.LMSCommit('');
        }
      }
      return initialized;
    },

    setComplete: function() {
      var lmsAPI = getAPI();
      if (lmsAPI && initialized) {
        lmsAPI.LMSSetValue('cmi.core.lesson_status', 'completed');
        lmsAPI.LMSSetValue('cmi.core.score.raw', '100');
        lmsAPI.LMSSetValue('cmi.core.score.min', '0');
        lmsAPI.LMSSetValue('cmi.core.score.max', '100');
        lmsAPI.LMSCommit('');
      }
    },

    setProgress: function(percent) {
      // SCORM 1.2 does not have a progress measure field
      // Just check completion threshold
      if (percent >= COMPLETION_THRESHOLD) {
        this.setComplete();
      }
    },

    setSessionTime: function(seconds) {
      var lmsAPI = getAPI();
      if (lmsAPI && initialized) {
        var hours = Math.floor(seconds / 3600);
        var mins = Math.floor((seconds % 3600) / 60);
        var secs = Math.floor(seconds % 60);
        var time = String(hours).padStart(4, '0') + ':' +
                   String(mins).padStart(2, '0') + ':' +
                   String(secs).padStart(2, '0');
        lmsAPI.LMSSetValue('cmi.core.session_time', time);
        lmsAPI.LMSCommit('');
      }
    },

    terminate: function() {
      var lmsAPI = getAPI();
      if (lmsAPI && initialized) {
        lmsAPI.LMSFinish('');
        initialized = false;
      }
    },

    COMPLETION_THRESHOLD: COMPLETION_THRESHOLD
  };
})();
`
  }

  // SCORM 2004
  return `/**
 * SCORM 2004 API Adapter
 * Generated by ProAnimate SCORM Exporter
 */
(function() {
  'use strict';

  var COMPLETION_THRESHOLD = ${completionThreshold / 100};
  var api = null;
  var initialized = false;

  function findAPI(win) {
    var attempts = 0;
    while (win && !win.API_1484_11 && attempts < 10) {
      attempts++;
      if (win.opener && win.opener !== win) {
        win = win.opener;
      } else if (win.parent && win.parent !== win) {
        win = win.parent;
      } else {
        break;
      }
    }
    return win ? win.API_1484_11 || null : null;
  }

  function getAPI() {
    if (api) return api;
    api = findAPI(window);
    if (!api && window.opener) {
      api = findAPI(window.opener);
    }
    return api;
  }

  window.ScormAdapter = {
    initialize: function() {
      var lmsAPI = getAPI();
      if (lmsAPI) {
        var result = lmsAPI.Initialize('');
        initialized = result === 'true' || result === true;
        if (initialized) {
          lmsAPI.SetValue('cmi.completion_status', 'incomplete');
          lmsAPI.SetValue('cmi.success_status', 'unknown');
          lmsAPI.Commit('');
        }
      }
      return initialized;
    },

    setComplete: function() {
      var lmsAPI = getAPI();
      if (lmsAPI && initialized) {
        lmsAPI.SetValue('cmi.completion_status', 'completed');
        lmsAPI.SetValue('cmi.success_status', 'passed');
        lmsAPI.SetValue('cmi.score.scaled', '1');
        lmsAPI.SetValue('cmi.score.raw', '100');
        lmsAPI.SetValue('cmi.score.min', '0');
        lmsAPI.SetValue('cmi.score.max', '100');
        lmsAPI.Commit('');
      }
    },

    setProgress: function(percent) {
      var lmsAPI = getAPI();
      if (lmsAPI && initialized) {
        lmsAPI.SetValue('cmi.progress_measure', String(percent / 100));
        lmsAPI.Commit('');
        if (percent >= COMPLETION_THRESHOLD * 100) {
          this.setComplete();
        }
      }
    },

    setSessionTime: function(seconds) {
      var lmsAPI = getAPI();
      if (lmsAPI && initialized) {
        var hours = Math.floor(seconds / 3600);
        var mins = Math.floor((seconds % 3600) / 60);
        var secs = Math.floor(seconds % 60);
        var time = 'PT' + hours + 'H' + mins + 'M' + secs + 'S';
        lmsAPI.SetValue('cmi.session_time', time);
        lmsAPI.Commit('');
      }
    },

    terminate: function() {
      var lmsAPI = getAPI();
      if (lmsAPI && initialized) {
        lmsAPI.Terminate('');
        initialized = false;
      }
    },

    COMPLETION_THRESHOLD: COMPLETION_THRESHOLD
  };
})();
`
}

